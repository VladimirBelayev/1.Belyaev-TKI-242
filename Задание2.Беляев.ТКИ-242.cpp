#include <iostream>
#include <list>
#include <iterator>

int main() {
    std::list<int> L;
    int n;

    // 1. Ввод количества элементов с проверкой кратности 4
    std::cout << "Введите количество элементов списка (должно быть кратно 4): ";
    if (!(std::cin >> n) || n <= 0 || n % 4 != 0) {
        std::cerr << "Ошибка: количество элементов должно быть положительным и кратным 4!" << std::endl;
        return 1;
    }

    // 2. Ввод элементов списка пользователем
    std::cout << "Введите " << n << " чисел через пробел: ";
    for (int i = 0; i < n; ++i) {
        int val;
        std::cin >> val;
        L.push_back(val);
    }

    // 3. Переменная для отслеживания текущего порядкового номера (1-based)
    int current_pos = n / 2;
    // 4. Цикл удаления
    // Мы не храним итератор r в заголовке цикла, а создаем его динамически, чтобы после каждого удаления восстанавливать его в исходное состояние.
    while (current_pos > 0) {

        // Каждый раз заново находим актуальное положение итераторов для текущей позиции
        auto half_end = L.begin();
        std::advance(half_end, current_pos); // Сдвигаем прямой итератор на текущую рабочую позицию
        std::list<int>::reverse_iterator r(half_end); // Создаем наш reverse_iterator строго для этой итерации
        // Так как выражение --(++r).base() удаляет элемент слева от r (current_pos - 1),мы заходим в удаление, только когда текущая позиция ЧЁТНАЯ (чтобы удалилась НЕЧЁТНАЯ).
        if (current_pos % 2 == 0) { 
            if (current_pos == 2) {
                L.erase(L.begin());
            }
            else {
                L.erase(--(++r).base());
            }
            // После удаления элемента размер первой половины уменьшился на 1
            --current_pos;
        }
        // Движемся к началу списка
        // Если удаление произошло, мы уже уменьшили current_pos на 1 выше, поэтому здесь уменьшаем только для четных шагов
        --current_pos;
    }
    // 5. Вывод итогового списка в консоль
    std::cout << "Результат работы программы: ";
    for (int val : L) {
        std::cout << val << " ";
    }
    return 0;
}
